"""Sphinx configuration for the gtfs-ingest documentation.

Build with::

    python -m sphinx -b html docs docs/_build/html

or ``make html`` / ``make.bat html`` from inside ``docs/``.

The API reference is generated by ``autodoc``, which *imports* the package -
every module under :mod:`gtfs_ingest` must therefore be importable in the
environment running the build (install the project first, ideally editable:
``pip install -e ".[docs]"``).
"""

from __future__ import annotations

import os
import sys
from datetime import date
from pathlib import Path

# The package lives one level above docs/. Prepending the repo root makes the
# build work even when gtfs-ingest is not installed into the environment.
REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from gtfs_ingest import __version__ as _version  # noqa: E402

# -- Project information -----------------------------------------------------

project = "gtfs-ingest"
author = "Victor Panda"
copyright = f"{date.today():%Y}, {author}"
version = _version
release = _version

# -- General configuration ---------------------------------------------------

extensions = [
    "sphinx.ext.autodoc",  # pull docstrings out of the package
    "sphinx.ext.napoleon",  # understand Google-style Args:/Returns:/Attributes:
    "sphinx.ext.viewcode",  # "[source]" links next to every object
    "sphinx.ext.intersphinx",  # link pandas/shapely/... types to their own docs
    "sphinx.ext.todo",
    "myst_parser",  # let the existing Markdown docs into the build
    "sphinx_copybutton",  # copy button on the many CLI snippets
    "sphinxcontrib.mermaid",  # render ```mermaid fences as diagrams
]

# Smart typography is actively harmful here: it rewrites the ``--`` in a CLI
# flag mentioned in prose (``--dry-run``) into an en dash, so anything copied
# out of the docs fails to parse. Straight quotes and literal dashes it is.
smartquotes = False

templates_path = ["_templates"]
exclude_patterns = ["_build", "Thumbs.db", ".DS_Store", "plans"]

# Both parsers are active: .md goes through MyST, .rst through docutils.
source_suffix = {".rst": "restructuredtext", ".md": "markdown"}

# The README carries several top-level (``#``) sections rather than one, so
# documents may legitimately lack a single promotable title; toctree entries
# below supply explicit captions instead.
suppress_warnings = ["myst.header", "myst.xref_missing"]

# -- Autodoc -----------------------------------------------------------------

autodoc_default_options = {
    "members": True,
    "show-inheritance": True,
    # Source order beats alphabetical here: modules are written top-down, with
    # the public entry point first and helpers after it.
    "member-order": "bysource",
}

# Signatures stay readable (pandas/geopandas annotations are long); the types
# are rendered into the parameter list instead, merged with the Args: section.
autodoc_typehints = "description"
autodoc_typehints_description_target = "documented_params"
autodoc_preserve_defaults = True

# Module-level constants (MAX_FREQUENCY_RUNS, GROUP_KEY, ...) are documented
# with ``#:`` comments throughout the codebase - keep their values visible.
autodoc_member_order = "bysource"

# -- Napoleon ----------------------------------------------------------------

napoleon_google_docstring = True
napoleon_numpy_docstring = False
napoleon_include_init_with_doc = True
napoleon_use_admonition_for_notes = True
napoleon_use_admonition_for_examples = True
napoleon_use_rtype = False  # fold the return type into the Returns: line

# -- MyST --------------------------------------------------------------------

myst_enable_extensions = [
    "colon_fence",  # ::: fences, friendlier than ``` inside Markdown
    "deflist",
    "fieldlist",
    "linkify",  # bare URLs in the Markdown docs become links
    "substitution",
    "tasklist",
]
# Give every heading in the included Markdown an anchor, so the in-page
# tables of contents and cross-document links resolve.
myst_heading_anchors = 4
# ```mermaid fences are diagrams, not code: route them to the mermaid
# directive so they render in the site exactly as they do on GitHub.
myst_fence_as_directive = ["mermaid"]

# -- Intersphinx -------------------------------------------------------------

#: Set ``DOCS_NO_INTERSPHINX=1`` to skip the inventory downloads entirely.
#: CI does this: the strict (``-W``) build is there to catch *docstring markup*
#: regressions, and it must not go red because someone else's docs site is
#: briefly unreachable. Local builds keep the cross-links.
_intersphinx_enabled = os.environ.get("DOCS_NO_INTERSPHINX", "") not in ("1", "true", "yes")

intersphinx_mapping = {
    "python": ("https://docs.python.org/3", None),
    "numpy": ("https://numpy.org/doc/stable/", None),
    "pandas": ("https://pandas.pydata.org/docs/", None),
    "geopandas": ("https://geopandas.org/en/stable/", None),
    "shapely": ("https://shapely.readthedocs.io/en/stable/", None),
    "sqlalchemy": ("https://docs.sqlalchemy.org/en/20/", None),
    "networkx": ("https://networkx.org/documentation/stable/", None),
    "pydantic": ("https://docs.pydantic.dev/latest/", None),
}
if not _intersphinx_enabled:
    intersphinx_mapping = {}

# Bound the wait when an inventory is slow or unreachable (offline builds).
intersphinx_timeout = 5

# -- HTML output -------------------------------------------------------------

html_theme = "furo"
html_title = f"gtfs-ingest {version}"
html_static_path = ["_static"]
html_theme_options = {
    "navigation_with_keys": True,
}

# -- LaTeX / PDF output ------------------------------------------------------

latex_documents = [
    (
        "index",
        "gtfs-ingest.tex",
        "gtfs-ingest: GTFS + OSM Transit Analysis Pipeline",
        author,
        "manual",
    ),
]
latex_elements = {
    "papersize": "letterpaper",
    "pointsize": "10pt",
}
